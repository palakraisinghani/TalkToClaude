export function icon(name, size = 18) {
  return `<svg class="ic" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name] ?? ""}</svg>`;
}

/** Put an icon in an element, keeping any text label after it. */
export function setIcon(el, name, size) {
  const old = el.querySelector(":scope > svg.ic");
  if (old) old.outerHTML = icon(name, size);
  else el.insertAdjacentHTML("afterbegin", icon(name, size));
}
